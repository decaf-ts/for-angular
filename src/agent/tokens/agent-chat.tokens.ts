/**
 * @module for-angular/agent/tokens/agent-chat.tokens
 * @summary Injection tokens for the agent chat surface (`ngx-decaf-agent-chat`).
 * @description Exposes the {@link AGENT_CHAT_TRANSPORT} override point —
 * the single seam for swapping the default {@link GraphRunAgentChatTransport}
 * for an alternative {@link AgentChatTransport} implementation such as a
 * scripted storybook transport or the optional `@ai-sdk/angular` peer — plus
 * the session-id prefix {@link AgentChatService} uses for generated
 * conversation ids.
 */
import { InjectionToken, inject } from "@angular/core";
import { GraphRunAgentChatTransport } from "../services/GraphRunAgentChatTransport";
import type { AgentChatTransport } from "../types";

/**
 * Root-provided transport used by {@link AgentChatService} to create, stream,
 * replay, and cancel agent runs.
 *
 * Defaults to the graph-run backend transport; provide an alternative value at
 * component/environment level to plug in a custom transport (e.g. the optional
 * `@ai-sdk/angular` peer or a scripted storybook transport).
 */
export const AGENT_CHAT_TRANSPORT = new InjectionToken<AgentChatTransport>(
  "AGENT_CHAT_TRANSPORT",
  {
    providedIn: "root",
    factory: () => inject(GraphRunAgentChatTransport),
  },
);

/** Prefix for session ids generated by {@link AgentChatService} (`agent-chat-<epoch>-<seq>`). */
export const AGENT_CHAT_SESSION_PREFIX = "agent-chat";
