/**
 * @module for-angular/agent/types
 * @summary Transport contract and read-model views for the agent chat surface
 * (`ngx-decaf-agent-chat`, slice U3 of SAA-836).
 * @description Defines the {@link AgentChatTransport} abstraction the chat UI
 * consumes (default implementation: {@link GraphRunAgentChatTransport}, which
 * talks to the graph run HTTP/SSE backend), the immutable conversation state
 * the envelope fold produces ({@link AgentChatMessageView},
 * {@link AgentChatRoundtripTelemetry}, {@link AgentChatStructuredObjectView}),
 * and the request/configuration shapes flowing between them.
 *
 * The module is intentionally free of Angular and decaf persistence imports so
 * both the default transport and scripted storybook transports can implement
 * {@link AgentChatTransport} against the same contract.
 */
import type { GraphRunEventEnvelope } from "@decaf-ts/as-graph/shared";

/** Role a {@link AgentChatMessageView} plays in the transcript. */
export type AgentChatRole = "user" | "assistant" | "system" | "error";

/** File attached to a chat message (UI-only metadata; contents are never read). */
export interface AgentChatAttachment {
  /** Stable chip identifier generated by the composer (e.g. `attachment:3`). */
  id: string;
  /** Original file name as selected by the user. */
  name: string;
  /** MIME type; falls back to `application/octet-stream` when unknown. */
  mime: string;
  /** File size in bytes. */
  size: number;
}

/** Knowledge-base entry the composer can attach to outgoing messages. */
export interface AgentChatKnowledgeSource {
  /** Backend identifier passed through as `knowledgeBaseIds` on the run inputs. */
  id: string;
  /** Human-readable label rendered by the knowledge-base selector. */
  label: string;
}

/** One transcript entry produced by the user, the agent fold, or an error path. */
export interface AgentChatMessageView {
  /** Unique message id (`user:<n>` / `error:<n>` for local entries, `<runId>:<sequence>` for folded envelopes). */
  id: string;
  /** Which transcript column the message renders in. */
  role: AgentChatRole;
  /** Displayed text content. */
  content: string;
  /** Attachments the user attached to this message. */
  attachments: AgentChatAttachment[];
  /** Knowledge-base ids the user selected for this message. */
  knowledgeSourceIds: string[];
  /** ISO timestamp the message was created or received. */
  createdAt: string;
  /** Run the message belongs to; set for folded agent/error messages. */
  runId?: string;
  /** While `true` the message is a placeholder awaiting the agent's response and can be replaced in place. */
  pending?: boolean;
  /** Action names the agent reported alongside its response (rendered as chips). */
  actions?: string[];
}

/** Lifecycle status of a chat roundtrip's underlying graph run. `replayed` is
 * reserved and never set by the current fold pipeline — replays are flagged
 * via `replayed` on the telemetry row instead. */
export type AgentChatRoundtripStatus =
  | "queued"
  | "running"
  | "succeeded"
  | "failed"
  | "cancelled"
  | "replayed";

/** Per-run telemetry surfaced by the chat's telemetry strip. */
export interface AgentChatRoundtripTelemetry {
  /** Graph run the telemetry row tracks. */
  runId: string;
  /** Current lifecycle status of the run. */
  status: AgentChatRoundtripStatus;
  /** `true` when the roundtrip was produced by a replay instead of a live send. */
  replayed?: boolean;
  /** ISO timestamp of the `WORKFLOW_STARTED` envelope. */
  startedAt?: string;
  /** ISO timestamp of the terminal envelope. */
  finishedAt?: string;
  /** Total nodes queued by the run (`NODE_QUEUED` count). */
  nodeCount?: number;
  /** Nodes that completed successfully (`NODE_COMPLETED` count). */
  completedNodeCount?: number;
  /** Number of `GRAPH_RUN_LOG` envelopes received. */
  logLines?: number;
  /** First error carried by a failed run or node. */
  error?: { name?: string; message?: string };
}

/** Structured object (use-object style) extracted from a run's `NODE_OUTPUT` payload. */
export interface AgentChatStructuredObjectView {
  /** Run that produced the structured value. */
  runId: string;
  /** Raw structured payload rendered by `GraphIoViewerComponent`. */
  value: unknown;
}

/** Full payload a {@link AgentChatTransport.send} turns into a graph run. */
export interface AgentChatSendRequest {
  /** Inline workflow document; takes precedence over `workflowId`. */
  workflow?: unknown;
  /** Backend workflow id used when no inline document is provided. */
  workflowId?: string;
  /** Trimmed user message text. */
  message: string;
  /** UI-only attachment metadata forwarded as run inputs. */
  attachments: AgentChatAttachment[];
  /** Selected knowledge-base ids forwarded as run inputs. */
  knowledgeSourceIds: string[];
  /** Conversation session id (`agent-chat-…` unless configured). */
  sessionId: string;
  /** Resolved `loggedUser` id, or `null` when unauthenticated. */
  userId: string | null;
}

/** Minimal handle identifying a created run for streaming, replay, and cancel. */
export interface AgentChatRunDescriptor {
  /** Backend run id. */
  runId: string;
  /** SSE events URL returned by `POST /graph/runs`. */
  eventsUrl: string;
}

/** Callbacks a transport invokes while streaming a run's envelopes. */
export interface AgentChatTransportHandlers {
  /** Called for every (live or replayed) non-terminal envelope, in sequence order. */
  onEvent(envelope: GraphRunEventEnvelope): void;
  /** Called once per run with the terminal envelope (`WORKFLOW_COMPLETED`/`FAILED`/`CANCELLED`). */
  onTerminal(envelope: GraphRunEventEnvelope): void;
  /** Called on SSE/connectivity errors; the transport may keep retrying afterwards. */
  onError(error: unknown): void;
}

/**
 * Transport abstraction for the agent chat: creates runs, streams their
 * envelopes through {@link AgentChatTransportHandlers}, and cancels live runs.
 * The default implementation is {@link GraphRunAgentChatTransport}; the
 * `AGENT_CHAT_TRANSPORT` injection token is the override point for alternative
 * transports (e.g. a scripted storybook transport or an `@ai-sdk/angular`
 * peer).
 */
export interface AgentChatTransport {
  /**
   * Creates a run for the request and resolves to its descriptor as soon as
   * the backend accepts it; envelope streaming continues in the background.
   */
  send(
    request: AgentChatSendRequest,
    handlers: AgentChatTransportHandlers
  ): Promise<AgentChatRunDescriptor>;
  /** Re-streams a previously created run's recorded events from sequence zero. */
  replay(
    descriptor: AgentChatRunDescriptor,
    handlers: AgentChatTransportHandlers
  ): Promise<void>;
  /** Requests cancellation of a live run (idempotent for terminal runs). */
  cancel(runId: string): Promise<void>;
}

/** Component-provided defaults consumed by {@link AgentChatService}. */
export interface AgentChatConfiguration {
  /** Backend workflow id (`null` clears a previously configured value). */
  workflowId?: string | null;
  /** Conversation session id; generated on first send when unset. */
  sessionId?: string | null;
  /** Explicit user id override; `null` forces anonymous sends. */
  userId?: string | null;
}
